#![allow(dead_code)]

//! Архитектурно-независимый контракт межъядерных прерываний (IPI).
//!
//! IPI — механизм доставки ядром управления на ДРУГИЕ ядра: TLB-shootdown,
//! кик планировщика, останов. Контракт сознательно минимален: отправка по
//! индексу ядра (слот per-CPU области), широковещательная отправка всем
//! онлайновым кроме себя, битмаска онлайна. Вся механика контроллера —
//! собственность порта:
//!
//!   - x86_64: LAPIC ICR (xAPIC: MMIO 0x300/0x310; x2APIC: MSR 0x830),
//!     физический режим дестинейшена, edge/assert;
//!   - ARM64: GICv3 — SGI (INTID 0..15), групповая отправка через
//!     IC_SGI1R_EL1 (affinity-поля кодируют целевые ядра; per-INTID
//!     ack — ICC_SGI1R без EOI, SGI обслуживаются как обычные прерывания);
//!   - RISC-V: IMSIC (S-режим) — запись в CSR stopei чужого vs-select...;
//!     фактически MSI-запись в клепотих чужого ядра (sw-file), INTID =
//!     семантика IPI.
//!
//! ПРОТОКОЛ ЗАВИСИМЫХ ДЕЙСТВИЙ (TLB-shootdown) не входит в контракт:
//! «отправь IPI и дождись подтверждений» — политика надстройки (x86_64:
//! kernel_x86::ipi — очередь + поколение + per-CPU ack). Порты обязаны
//! лишь гарантировать ДОСТАВКУ семантики `IpiKind` на все онлайновые
//! ядра при включённых прерываниях на них.

/// Семантика межъядерного прерывания.
///
/// Вектор/INTID — собственность порта (x86_64: старшие векторы IDT,
/// зарезервированные под IPI; GICv3: выделенные SGI INTID). Общий слой
/// оперирует только смыслом.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IpiKind {
    /// TLB shootdown: получатель обязан дренить очередь инвалидаций
    /// (протокол порта) и подтвердить обработку.
    TlbShootdown,
    /// Кик цикла планировщика (reschedule; v1 — no-op, доставка
    /// зарезервирована).
    Reschedule,
    /// Остановка/парковка ядра.
    Halt,
}

/// Ошибка отправки IPI.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IpiError {
    /// Целевое ядро не онлайн (не отмечено [`IpiController::mark_current_online`])
    /// или индекс вне пределов.
    BadTarget,
    /// Контроллер IPI не готов (LAPIC/GIC/IMSIC не инициализированы).
    NotReady,
}

/// Контроллер межъядерных прерываний (переносимый контракт).
///
/// Реализуется портом (x86_64: kernel_x86::ipi); общий слой получает
/// доступ через хуки регистрации порта. Все операции над ТЕКУЩИМ ядром
/// (слот определяется аппаратно: GS base / affinity / hartid) — отправка
/// может адресовать любое онлайн-ядро по его слоту.
pub trait IpiController: Sync {
    /// Слот текущего ядра; `None` — per-CPU идентификация ещё не
    /// установлена (ранний бут: единственное ядро, IPI не нужны).
    fn current_cpu(&self) -> Option<usize>;

    /// Число поддерживаемых слотов ядер (ёмкость битмасок).
    fn cpu_count(&self) -> usize;

    /// Битмаска онлайновых ядер: бит i — слот i принял per-CPU
    /// инициализацию, отметил онлайн и ОТВЕЧАЕТ на IPI (прерывания
    /// включены). Отправитель имеет право ждать подтверждений только от
    /// ядер из этой маски.
    fn online_mask(&self) -> u64;

    /// Отметить ТЕКУЩЕЕ ядро онлайн (вызывается портом/фронтом после
    /// per-CPU инициализации, непосредственно перед включением
    /// прерываний — с этого момента ядро обязано подтверждать IPI).
    fn mark_current_online(&self);

    /// Отправить IPI конкретному ядру по слоту.
    fn send_to_cpu(&self, cpu: usize, kind: IpiKind) -> Result<(), IpiError>;

    /// Отправить IPI всем онлайновым ядрам, кроме текущего.
    /// Ошибки отдельных доставок (ядро ушло в оффлайн между чтением
    /// маски и отправкой) не фатальны: получатель, не обработавший IPI,
    /// подтверждение не выставит — надстройка обязана иметь таймаут.
    fn broadcast_others(&self, kind: IpiKind) -> Result<(), IpiError>;
}
